/* ============================================================================
 * fetch-tech-icons.js — vendors the brand marks used by the Skills explorer.
 * ----------------------------------------------------------------------------
 * Reads the id -> slug table below, downloads each mark from
 * cdn.simpleicons.org and writes js/modules/icons.brand.js as a plain JS
 * object of path data. Run it again whenever you add a branded technology:
 *
 *      node tools/fetch-tech-icons.js
 *
 * Why vendored instead of hot-linking the CDN: the site has to work offline and
 * from file://, and the CDN rate-limits bursts, which would show up as missing
 * icons for a recruiter. Path data from Simple Icons is CC0; the trademarks
 * themselves stay with their owners and are used here only to name the
 * technology. Marks that no longer exist on that CDN (Microsoft, Adobe, AWS,
 * Canva, Tableau, SAS, SPSS) get hand-drawn generic glyphs in
 * js/modules/icons.js instead — an invented logo is worse than a plain one.
 * ==========================================================================*/
'use strict';
const fs = require('fs');
const path = require('path');
const https = require('https');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'js', 'modules', 'icons.brand.js');

/* skill id (js/content/skills.data.js) -> simpleicons.org slug */
const SLUGS = {
  c: 'c',
  cpp: 'cplusplus',
  python: 'python',
  php: 'php',
  javascript: 'javascript',
  typescript: 'typescript',
  r: 'r',
  html5: 'html5',
  css3: 'css',
  bootstrap: 'bootstrap',
  tailwind: 'tailwindcss',
  react: 'react',
  node: 'nodedotjs',
  express: 'express',
  wordpress: 'wordpress',
  wix: 'wix',
  flutter: 'flutter',
  opencv: 'opencv',
  mediapipe: 'mediapipe',
  tensorflow: 'tensorflow',
  mysql: 'mysql',
  firebase: 'firebase',
  supabase: 'supabase',
  fastapi: 'fastapi',
  git: 'git',
  svg: 'svg',
  threejs: 'threedotjs',
  numpy: 'numpy',
  google: 'google',
  coursera: 'coursera'
};

function get(url) {
  return new Promise(function (resolve, reject) {
    https.get(url, { headers: { 'User-Agent': 'portfolio-icon-fetch/1.0' } }, function (res) {
      if (res.statusCode !== 200) { res.resume(); resolve(null); return; }
      var body = '';
      res.setEncoding('utf8');
      res.on('data', function (chunk) { body += chunk; });
      res.on('end', function () { resolve(body); });
    }).on('error', function () { resolve(null); });
  });
}

/* keep only the geometry: drop the fill attribute (CSS tints it) and the label */
function pathsOf(svg) {
  var out = [];
  var re = /<path[^>]*d="([^"]+)"[^>]*\/>/g;
  var m;
  while ((m = re.exec(svg))) out.push(m[1]);
  return out;
}

async function main() {
  var ids = Object.keys(SLUGS);
  var found = {};
  var missing = [];
  for (var i = 0; i < ids.length; i++) {
    var id = ids[i];
    var svg = await get('https://cdn.simpleicons.org/' + SLUGS[id] + '/334155');
    var d = svg ? pathsOf(svg) : [];
    if (d.length) found[id] = d; else missing.push(id + ' (' + SLUGS[id] + ')');
    await new Promise(function (r) { setTimeout(r, 120); });
  }

  var body = Object.keys(found).sort().map(function (id) {
    return '    ' + JSON.stringify(id) + ': ' + JSON.stringify(found[id]);
  }).join(',\n');

  fs.writeFileSync(OUT,
    '/* GENERATED by tools/fetch-tech-icons.js — do not hand edit.\n' +
    '   Brand mark path data from simpleicons.org (CC0). Trademarks belong to\n' +
    '   their owners and are used here only to name the technology. */\n' +
    '(function (global) {\n' +
    "  'use strict';\n" +
    '  var App = global.App || (global.App = {});\n' +
    '  /* id -> array of 24x24 path "d" values, filled with currentColor */\n' +
    '  App.BRAND_ICONS = {\n' +
    body + '\n' +
    '  };\n' +
    '})(typeof window !== \'undefined\' ? window : globalThis);\n'
  );

  console.log('wrote ' + path.relative(ROOT, OUT) + ' — ' + Object.keys(found).length + ' marks');
  if (missing.length) console.log('not on the CDN (drawn by hand instead): ' + missing.join(', '));
}

main();
